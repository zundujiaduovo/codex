function c=leo_v15_certificate_result(s,o)
% Compatibility with the original benchmark exporter; certificate work is separate.
finiteLower=s.lower; if ~isfinite(finiteLower), finiteLower=NaN; end
g=max(0,s.upper-finiteLower); relative=g/max(s.upper,eps);
c=struct('version','V16 original-service branch-and-price','lower',finiteLower,'upper',s.upper, ...
    'absoluteGap',g,'relativeGap',relative,'gapTargetMet',isfinite(finiteLower) && g<=max(o.absoluteGap,o.relativeGap*max(s.upper,eps)), ...
    'status',s.status,'phase',s.phase,'fairnessFloor',s.floor,'options',o, ...
    'problemDataSnapshot',s.problemData,'incumbentX',s.incumbentX,'incumbentService',s.incumbentService, ...
    'nodesProcessed',s.nodesProcessed,'openNodeCount',numel(s.queue)+~isempty(s.active), ...
    'pricingComplete',s.rootLPComplete,'rootConfigurationLPComplete',s.rootLPComplete, ...
    'rootConfigurationUpper',s.rootConfigurationUpper,'branchTrace',s.trace, ...
    'pricingNodes',s.pricingNodes,'pricingCalls',s.blockCalls,'elapsedSeconds',s.elapsedSeconds, ...
    'baselineUpper',s.baselineUpper,'boundSchemaVersion',3,'upperBoundKind','ORIGINAL configuration LP and binary branch-and-price', ...
    'scope','Fixed ORIGINAL certified-service model; true common-beam interference and log(1+SINR), floating point outward guards. Unclosed trees retain their valid upper bounds. No stochastic-capacity claim.');
if strcmp(s.phase,'throughput')
    c.lowerBits=c.lower*1e6; c.upperBits=c.upper*1e6; c.absoluteGapBits=g*1e6;
    c.targetRelativeGap=o.relativeGap; c.targetAbsoluteGapBits=o.absoluteGap*1e6;
    c.pricingStatus=c.status; c.infeasibilityCertified=~isfinite(finiteLower) && isempty(s.active) && isempty(s.queue);
    c.kind=c.upperBoundKind;
end
end
